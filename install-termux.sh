#!/usr/bin/env bash
# Install OPENCODE-LOCAL on Android/Termux.
#   llama.cpp: built natively in Termux (fastest).
#   OpenCode:  official release binary inside Debian (proot-distro), because it needs glibc.
set -euo pipefail
# shellcheck source=SCRIPTDIR/lib/common.sh
source "$(dirname "$0")/lib/common.sh"

DISTRO="debian"
GUEST_REPO="/opt/opencode-local"

usage() {
  cat <<EOF
Usage: $(basename "$0") [options]

  -n, --dry-run      print every step without changing anything
      --skip-deps    do not run pkg install
      --no-llama     skip the native llama.cpp build
      --no-opencode  skip Debian and OpenCode (llama.cpp only)
      --from-source  build OpenCode from source inside Debian instead of installing
                     the official release binary (slow, needs much more RAM and network)
      --update       after git pull: refresh config, MCP tools and launcher only (no rebuilds)
EOF
}

skip_deps=0 no_llama=0 no_opencode=0 update=0 prebuilt=1
while [[ $# -gt 0 ]]; do
  case "$1" in
    -n|--dry-run) DRY_RUN=1; shift ;;
    --skip-deps) skip_deps=1; shift ;;
    --no-llama) no_llama=1; shift ;;
    --no-opencode) no_opencode=1; shift ;;
    --prebuilt-opencode) prebuilt=1; shift ;; # default since 1.1, kept for old instructions
    --from-source) prebuilt=0; shift ;;
    --update) update=1 skip_deps=1 no_llama=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) usage; exit 2 ;;
  esac
done

is_termux || [[ "$DRY_RUN" == 1 ]] || die "this script must run inside Termux"
termux_bin="${PREFIX:-/data/data/com.termux/files/usr}/bin"

log "OPENCODE-LOCAL installer (termux)$([[ "$DRY_RUN" == 1 ]] && echo ' [dry run]')"

# 1. Termux packages
if [[ "$skip_deps" == 0 ]]; then
  run pkg update -y
  run pkg install -y git cmake clang make curl unzip jq proot-distro
fi

# 2. llama.cpp natively in Termux
[[ "$no_llama" == 1 ]] || build_llama_cpp "$termux_bin"

# 3. Debian proot with Bun + OpenCode
if [[ "$no_opencode" == 0 ]]; then
  # Ask proot-distro itself: the rootfs location differs between proot-distro versions.
  if proot-distro login "$DISTRO" -- true >/dev/null 2>&1; then
    log "proot-distro $DISTRO already installed"
  else
    run proot-distro install "$DISTRO"
  fi
  guest=(proot-distro login "$DISTRO" --bind "$REPO_ROOT:$GUEST_REPO" --)
  run "${guest[@]}" bash -c "apt-get update && apt-get install -y --no-install-recommends git curl unzip jq ca-certificates python3 gnupg ffmpeg"
  guest_args=(--skip-deps --no-llama)
  [[ "$update" == 1 ]] && guest_args+=(--config-only)
  [[ "$prebuilt" == 0 ]] && guest_args+=(--from-source)
  [[ "$DRY_RUN" == 1 ]] && guest_args+=(--dry-run)
  run "${guest[@]}" bash "$GUEST_REPO/install-linux.sh" "${guest_args[@]}"
fi

# 4. Termux-side helpers: model download + server run natively, OpenCode runs in Debian.
run mkdir -p "$OCL_HOME" "$OCL_STATE"
run install -m 0644 "$REPO_ROOT/ki-config/env.sh" "$OCL_HOME/env.sh"

launcher="$termux_bin/opencode-local"
if [[ "$DRY_RUN" == 1 ]]; then
  printf '\033[2m[dry-run]\033[0m write launcher %s\n' "$launcher" >&2
else
  cat > "$launcher" <<EOF
#!/data/data/com.termux/files/usr/bin/bash
# Generated by install-termux.sh. Starts llama-server natively if needed, then
# OpenCode inside Debian with ONLY the current project directory visible.
set -euo pipefail
case "\$PWD" in "\$HOME"|/|/sdcard|/storage/emulated/0)
  echo "[ocl] refusing to start in \$PWD - cd into a project directory first" >&2; exit 1 ;;
esac
# While the marker exists the model server stays up; afterwards it stops itself when idle.
marker="$OCL_STATE/sessions/\$\$"
mkdir -p "$OCL_STATE/sessions" && : > "\$marker"
trap 'rm -f "\$marker"; termux-wake-unlock 2>/dev/null || true' EXIT
"$REPO_ROOT/scripts/ensure-llama.sh"
termux-wake-lock 2>/dev/null || true
proot-distro login $DISTRO --bind "\$PWD:/work" -- bash -c 'cd /work && exec /root/.local/bin/opencode-local "\$@"' opencode-local "\$@"
EOF
  chmod 0755 "$launcher"
fi

[[ -n "${OCL_QUICKSTART:-}" ]] && exit 0  # quickstart.sh prints its own next steps
cat >&2 <<EOF

Done. Next steps (in Termux):
  1. scripts/fetch-model.sh qwen3-1.7b
  2. scripts/bench.sh                       # Phase 1: tokens/s
  3. mkdir -p ~/projects/myproject && cd ~/projects/myproject && opencode-local
  4. Stop the model when done: scripts/start-llama.sh --stop ; termux-wake-unlock
Then block Termux's network access in your firewall app (docs/security.md).
EOF
